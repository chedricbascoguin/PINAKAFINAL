const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.join(__dirname, '../dental-exam-suggestions.js'), 'utf8');
const pure = {module:{exports:{}}}; vm.runInNewContext(source, pure);
const recommend = pure.module.exports.recommendationFor;
assert.equal(recommend(''), '');
assert.match(recommend('Tooth #36: Caries / decay.'), /possible fillings/);
assert.match(recommend('Bleeding gums.'), /gums checked/);
assert.doesNotMatch(recommend('No caries. No bleeding gums.'), /possible fillings|gums checked/);
assert.match(recommend('No caries but bleeding gums.'), /gums checked/);
assert.doesNotMatch(recommend('No caries but bleeding gums.'), /possible fillings/);
assert.match(recommend('Tooth #11: Extracted / missing.'), /options to replace/);
const plan = recommend('Tooth #36: Caries / decay.\nTeeth #11, #12: For extraction assessment.');
assert.match(plan, /Have tooth #36 checked for possible fillings/);
assert.match(plan, /whether teeth #11, #12 can be saved or need removal/);
assert(plan.split('\n').every(line => line.length < 140));
assert(plan.split(/\s+/).length < 80);
assert.doesNotMatch(recommend('Caries absent. Bleeding not present.'), /possible fillings|gums checked/);
assert.doesNotMatch(recommend('Normal gums. Good oral hygiene.'), /need removal|possible fillings|gums checked/);
assert.match(plan, /^Have tooth #36/);
function field(value='') { return {value, hidden:false, checked:false, handlers:{}, addEventListener(name, handler){ this.handlers[name]=handler; }}; }
const elements = {findings:field(),recommendation:field(),exam_approved:field(),recommendation_mode:field(),oral_hygiene:field('Fair'),gum_condition:field('Not assessed'),odontogram_json:field('{}')};
Object.entries(elements).forEach(([name, element]) => element.name=name);
const help = field(), restore = field();
const form = {elements, handlers:{}, addEventListener(name, handler){ this.handlers[name]=handler; }};
const context = {module:{exports:{}},document:{querySelector:()=>({closest:()=>form}),getElementById:id=>id==='dental_recommendation_help'?help:restore}};
vm.runInNewContext(source, context);
assert.match(elements.recommendation.value, /gums checked/);
elements.findings.value='Tooth #36: Caries.';
elements.findings.handlers.input();
assert.match(elements.recommendation.value,/possible fillings/);
elements.recommendation.value='Custom dentist recommendation';
elements.recommendation.handlers.input();
elements.findings.value='Bleeding gums'; elements.findings.handlers.input();
assert.equal(elements.recommendation.value,'Custom dentist recommendation');
assert.equal(elements.recommendation_mode.value,'manual');
assert.equal(restore.hidden,false);
restore.handlers.click();
assert.match(elements.recommendation.value,/gums checked/);
assert.equal(elements.recommendation_mode.value,'automatic');
elements.exam_approved.checked=true;
elements.odontogram_json.value='{"11":["missing"]}';
form.handlers.change({target:elements.odontogram_json});
assert.match(elements.findings.value,/#11: Extracted/);
assert.equal(elements.exam_approved.checked,false);
assert.match(elements.recommendation.value,/options to replace/);
console.log('Automatic recommendations passed: findings changes, negation, tooth marks, editable overrides, restore and renewed approval.');

// Loading history twice must not duplicate generated findings.
form.handlers['dental:chart-loaded']();
form.handlers['dental:chart-loaded']();
assert.equal((elements.findings.value.match(/Oral hygiene:/g) || []).length, 1);
assert.equal((elements.findings.value.match(/#11: Extracted/g) || []).length, 1);
// A changed chart regenerates the recommendation even after a manual edit.
elements.recommendation.value='Old custom plan';
elements.recommendation.handlers.input();
elements.odontogram_json.value='{"11":["filling"],"36":["caries"]}';
form.handlers.change({target:elements.odontogram_json});
assert.match(elements.findings.value,/#11: Filled/);
assert.doesNotMatch(elements.findings.value,/#11: Extracted/);
assert.match(elements.recommendation.value,/tooth #36.*possible fillings/);
assert.equal(elements.recommendation_mode.value,'automatic');
assert.equal(elements.exam_approved.checked,false);
console.log('History loading and chart edits regenerate findings and recommendations without duplicate or stale conditions.');

const dashboardSource = fs.readFileSync(path.join(__dirname, '../DentalDashboard.php'), 'utf8');
const detectionStart = dashboardSource.indexOf('function detectVisitTreatments(');
const detectionEnd = dashboardSource.indexOf('// One condition is stored', detectionStart);
const detection = {};
vm.runInNewContext(dashboardSource.slice(detectionStart, detectionEnd), detection);
const infer = (current, previous) => JSON.parse(JSON.stringify(detection.detectVisitTreatments(current, previous)));
assert.deepEqual(infer({'14':['filling'],'36':['missing']}, {'14':['filling'],'36':['missing']}), {procedure:[],extraction:[]});
assert.deepEqual(infer({'14':['filling'],'36':['missing'],'28':['caries']}, {'14':['caries'],'36':['to_extract']}), {procedure:['14'],extraction:['36']});
assert.deepEqual(infer({'14':['caries'],'36':['to_extract']}, {}), {procedure:[],extraction:[]});
assert.deepEqual(infer({'14':['caries']}, {'14':['filling']}), {procedure:[],extraction:[]});
assert.deepEqual(infer({'99':['filling'],'15':['filling'],'14':['filling']}, {}), {procedure:['14','15'],extraction:[]});
console.log('Treatment suggestions passed: historical colors excluded, new fillings/extractions detected, reverted changes cleared, invalid teeth ignored.');

const performedPlan = recommend('Tooth #12: Filled / Pasta (performed this visit).\nTooth #18: Filled / Pasta.');
assert.match(performedPlan, /aftercare instructions.*#12/);
assert.match(performedPlan, /existing fillings or crowns on tooth #18/);
assert.doesNotMatch(performedPlan, /existing fillings or crowns on tooth #12/);
const extractionPlan = recommend('Tooth #36: Extracted / missing (performed this visit).');
assert.match(extractionPlan, /aftercare instructions.*#36/);
assert.doesNotMatch(extractionPlan, /Ask about options to replace/);
console.log('Care plans distinguish completed treatment from historical tooth conditions.');

const detailsStart = dashboardSource.indexOf('function treatmentDetailSuggestions(');
const detailsEnd = dashboardSource.indexOf('// One condition is stored', detailsStart);
const detailContext = {};
vm.runInNewContext(dashboardSource.slice(detailsStart, detailsEnd), detailContext);
const extractionDetails = detailContext.treatmentDetailSuggestions('extraction','35, 36',{'35':['caries'],'36':['to_extract']},'');
assert.match(extractionDetails.care_extraction_reason, /Clinical indication not documented/);
assert.match(extractionDetails.care_extraction_reason, /#35: Caries/);
assert.equal(extractionDetails.care_anesthesia,undefined);
assert.equal(extractionDetails.care_complications,undefined);
assert.match(extractionDetails.care_extraction_notes, /#35, #36/);
const fillingDetails = detailContext.treatmentDetailSuggestions('procedure','14',{'14':['caries']},'Dental Filling');
assert.equal(fillingDetails.care_materials,'Not documented');
assert.match(fillingDetails.care_procedure_notes, /Dental Filling selected for #14/);
console.log('Editable treatment details use chart context without inventing materials, anesthesia, complications or clinical indication.');
